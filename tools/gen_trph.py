"""Generate TRPH's trophy abilities for Ghost Mode's DLC and the in-game data test (docs/features/trph.md).

Takes every trophy ability legacy changed (the six `def_item_trophies.xml` files: base game, Blood and Wine,
Hearts of Stone; regular and NG+) from `legacy-GM` whole and writes it into Ghost Mode's DLC with
on_conflict="replace": legacy dropped 1.32's nodes, so `extend` cannot express them, and Hearts of Stone's
abilities need `replace` anyway (extend empties them). Written whole means with legacy's weight nodes too:
the two Hearts of Stone abilities hold the crown's and the Conserved shaelmaar trophy's weight (WGT-05's
units, 0 -> 5 and 2 -> 5), which WGT's generators leave to this file (parallel-ports.md, section 5). The
shared `base_trophy_stats` (weight only) is WGT's and not written here. Abilities of a slice not ported yet
(PORTED, trph.md's port order) keep 5.x's definition.

The trophy items' TRPH fields (the `Quest` tag legacy removed from NG+'s Wyvern trophy `mq1051` and from the
Camerlengo's Seal) are `item_layer.py`'s TAGS. A regular-folder item of the base game or Blood and Wine that only
loses `Quest` (the Seal) is written here as a short `extend` entry, `<tags>-Quest</tags>` (the owner's form for a
tags-only change, PT4); `gen_item.py` writes the NG+ entries whole (it skips the names defined here).

New Game+ (`items_plus`): the ability as legacy's `items_plus` file has it (equal to the regular one).

    python tools/gen_trph.py --worktree DIR [--check | --verify]

Writes `items/gm_trph.xml` and `items_plus/gm_trph.xml` in Ghost Mode's DLC and the data test
`tests/gmTestsTrphData.ws` (--worktree, required). --check writes nothing and fails if a file is out of date.

--verify writes nothing and compares what the game reads (Ghost Mode's DLC over 5.x) with legacy's data, for
every ability of the six files (node by node, weight included; `base_trophy_stats` counted as WGT's) and the
`Quest` tag of every trophy item (both folders); entries of a slice not ported yet are counted, not compared.
Fails on any other difference or on a name defined twice in a DLC folder.
"""
import argparse, os, re, subprocess, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_ench import abilities, ability_stats  # noqa: E402
import gen_arm_items as arm  # noqa: E402  dlc_entries (ECON's extend entries resolved over 5.x's)
import paths  # noqa: E402  (tools/: the shared --worktree argument)

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DLC = "modGhostMode/files/dlc/dlcghostmode/data/gameplay/"
OUT = "gm_trph.xml"
TESTS = "modGhostMode/scripts/local/gm/tests/gmTestsTrphData.ws"
# (file pattern, feature, what)
FILES = [
    ("modGhostMode/files/gameplay/%s/def_item_trophies.xml", "TRPH-01", "base-game trophies"),
    ("modGhostMode/files/dlc/bob/data/gameplay/%s/def_item_trophies.xml", "TRPH-02", "Blood and Wine trophies"),
    ("modGhostMode/files/dlc/ep1/data/gameplay/%s/def_item_trophies.xml", "TRPH-03", "Hearts of Stone trophies (weight nodes legacy's: WGT-05, written here)"),
]
PORTED = {"TRPH-01", "TRPH-02", "TRPH-03"}
WGT = {"base_trophy_stats"}  # weight only: WGT's
# The 1.32 bonus attributes legacy's abilities dropped: a trophy on Roach must leave them as they were.
OLD = ["human_exp_bonus_when_fatal", "nonhuman_exp_bonus_when_fatal", "dismember_chance_mult", "bonus_herb_chance", "bonus_money"]


def git(*args):
    return subprocess.run(["git", "-C", REPO] + list(args), capture_output=True, check=True).stdout.decode("utf-8-sig")


def nocomments(text):
    return re.sub(r'(?s)<!--.*?-->', '', text)


def indent(body):
    out = []
    lines = [l.strip() for l in body.split("\n") if l.strip()]
    for i, l in enumerate(lines):
        out.append(("\t\t\t" if i in (0, len(lines) - 1) else "\t\t\t\t") + l)
    return "\n".join(out)


def changed(folder, pattern):
    """[(name, legacy body)] of the abilities legacy changed in a file, in legacy's order (WGT's left out)."""
    legacy = abilities(nocomments(git("show", "legacy-GM:" + pattern % folder)))
    vanilla = abilities(nocomments(git("show", "vanilla-5.x:" + pattern % folder)))
    return [(n, b) for n, b in legacy.items()
            if n not in WGT and ability_stats(b) != ability_stats(vanilla.get(n, ""))], vanilla


def build(folder):
    lines = ['<?xml version="1.0" encoding="UTF-8"?>', "<!-- Generated by tools/gen_trph.py from legacy-GM; do not edit. -->",
             "<redxml>", "\t<definitions>", "\t\t<abilities>"]
    for pattern, feature, what in FILES:
        if feature not in PORTED:
            continue
        found, vanilla = changed(folder, pattern)
        lines.append("\t\t\t<!-- %s: %s -->" % (feature, what))
        for n, b in found:
            head = '<ability name="%s"%s>' % (n, ' on_conflict="replace"' if n in vanilla else "")
            body = re.sub(r'^<ability\s+name="[^"]+"[^>]*>', head, b.strip())
            lines.append(indent(body))
    lines.append("\t\t</abilities>")
    stubs = quest_stubs(folder)
    if stubs:
        lines += ["\t\t<items>"] + ["\t\t\t" + x for x in stubs] + ["\t\t</items>"]
    lines += ["\t</definitions>", "</redxml>", ""]
    return "﻿" + "\n".join(lines).replace("\r\n", "\n").replace("\n", "\r\n")


def quest_stubs(folder):
    """Short `extend` entries for the regular folder's items legacy changed only by dropping `Quest` (not Hearts
    of Stone's: extend empties them)."""
    out = []
    if folder != "items":
        return out
    for pattern, feature, what in FILES:
        if feature not in PORTED or "/dlc/ep1/" in pattern:
            continue
        tags = {r: item_tags(r, pattern, folder) for r in ("vanilla-1.32", "legacy-GM", "vanilla-5.x")}
        for name, lt in tags["legacy-GM"].items():
            mt, vt = tags["vanilla-1.32"].get(name), tags["vanilla-5.x"].get(name)
            if mt is None or vt is None or "Quest" not in mt or "Quest" in lt or "Quest" not in vt:
                continue
            if sorted(x for x in mt if x != "Quest") != sorted(lt):
                continue
            out += ["<!-- %s: %s no longer a quest item (sellable, droppable) -->" % (feature, name),
                    '<item name="%s" on_conflict="extend">' % name, "\t<tags>-Quest</tags>", "</item>"]
    return out


def item_tags(ref, pattern, folder):
    """{item: tags} of a trophy file."""
    text = git("show", "%s:%s" % (ref, pattern % folder))
    out = {}
    for s, e, h in arm.item_spans(arm.blank_comments(text)):
        out[re.search(r'\bname\s*=\s*"([^"]+)"', h).group(1)] = arm.split_tags(arm.blank_comments(text[s:e]))
    return out


def nodes(body):
    """[(attribute, type, min)] of an ability body."""
    out = []
    for m in re.finditer(r'<(\w+)\b([^>]*?)/>', nocomments(body)):
        a = dict(re.findall(r'(\w+)\s*=\s*"([^"]*)"', m.group(2)))
        out.append((m.group(1), a.get("type", "base"), float(a.get("min", a.get("max", "0")))))
    return out


def trophy_items(ref, pattern, folder):
    """[(item, [abilities but base_trophy_stats])] of a trophy file."""
    text = git("show", "%s:%s" % (ref, pattern % folder))
    out = []
    for start, end, head in arm.item_spans(arm.blank_comments(text)):
        n = re.search(r'\bname\s*=\s*"([^"]+)"', head).group(1)
        b = re.search(r'(?s)<base_abilities>(.*?)</base_abilities>', arm.blank_comments(text[start:end]))
        abls = re.findall(r'<a>\s*(.*?)\s*</a>', b.group(1)) if b else []
        out.append((n, [a for a in abls if a not in WGT]))
    return out


def fmt(v):
    s = ("%.6f" % v).rstrip("0").rstrip(".")
    return s if "." in s else s + ".0"


def build_tests():
    """The data test: every ported trophy ability as the definitions give it, and each trophy's bonus on Geralt
    while it is on Roach (gmTestsTrph.ws's GMTestTrphNode and GMTestTrphEquip)."""
    head = ["// Generated by tools/gen_trph.py; do not edit. TRPH's data as the game reads it (docs/features/trph.md):",
            "// GMTestTrphData*: every ported trophy ability's nodes (legacy's) and the 1.32 bonus nodes it dropped (0);",
            "// GMTestTrphItems*: each trophy item's bonus, checked on Geralt while the trophy is on Roach.", ""]
    calls, equips, legacy = [], [], {}
    for pattern, feature, what in FILES:
        if feature not in PORTED:
            continue
        found, vanilla = changed("items", pattern)
        for n, b in found:
            lnodes = nodes(b)
            for attr, typ, v in lnodes:
                if attr == "weight":
                    continue
                calls.append("\tGMTestTrphNode('%s', '%s', \"%s\", %s);" % (n, attr, typ, fmt(v)))
            for attr, typ, v in nodes(vanilla.get(n, "")):
                if attr not in [x[0] for x in lnodes]:
                    calls.append("\tGMTestTrphNode('%s', '%s', \"%s\", 0.0);" % (n, attr, "zero"))
        legacy.update(changed("items", pattern)[0])  # shared abilities: Blood and Wine's griffin uses the prologue's
        for item, abls in trophy_items("vanilla-5.x", pattern, "items"):
            for a in abls:
                for attr, typ, v in nodes(legacy.get(a, "")):
                    if attr != "weight":
                        equips.append("\tGMTestTrphEquip('%s', '%s', '%s', \"%s\", %s);" % (item, a, attr, typ, fmt(v)))
    out = list(head)
    for prefix, rows in (("GMTestTrphData", calls), ("GMTestTrphItems", equips)):
        chunks = [rows[i:i + 50] for i in range(0, len(rows), 50)] or [[]]
        out.append("function %s()\n{" % prefix)
        out += ["\t%s%d();" % (prefix, i + 1) for i in range(len(chunks))]
        out.append("}\n")
        for i, c in enumerate(chunks):
            out.append("function %s%d()\n{" % (prefix, i + 1))
            out += c
            out.append("}\n")
    return "\n".join(out).replace("\n", "\r\n")


def dlc_entries(worktree, folder):
    """{ability: body} and {item: entry as the game reads it} of the DLC folder; names defined twice."""
    abls, dup = {}, []
    d = os.path.join(worktree, DLC, folder)
    seen = {}
    for f in sorted(os.listdir(d)):
        if not f.endswith(".xml"):
            continue
        text = open(os.path.join(d, f), encoding="utf-8-sig").read()
        for n, e in abilities(nocomments(text)).items():
            if n in abls:
                dup.append("ability %s in %s and %s" % (n, seen[n], f))
            abls[n], seen[n] = e, f
    return abls, arm.dlc_entries(worktree, folder)[0], dup


def verify(worktree):
    bad = 0
    for folder in ["items", "items_plus"]:
        gm_a, gm_i, dup = dlc_entries(worktree, folder)
        for x in dup:
            print("DUPLICATE %s: %s" % (folder, x))
            bad = 1
        counts = {}

        def count(k):
            counts[k] = counts.get(k, 0) + 1

        for pattern, feature, what in FILES:
            path = pattern % folder
            ltext, vtext = git("show", "legacy-GM:" + path), git("show", "vanilla-5.x:" + path)
            legacy, vanilla = abilities(nocomments(ltext)), abilities(nocomments(vtext))
            for name, body in legacy.items():
                final = gm_a.get(name, vanilla.get(name))
                if name in WGT:
                    count("base_trophy_stats: WGT's")
                    continue
                if ability_stats(final or "") == ability_stats(body):
                    count("abilities equal to legacy's (weight included)")
                elif feature not in PORTED:
                    count("%s not ported yet" % feature)
                else:
                    a, b = ability_stats(final or ""), ability_stats(body)
                    print("DIFF %s: ability %s\n  port only:   %s\n  legacy only: %s" % (
                        folder, name, [x for x in a if x not in b], [x for x in b if x not in a]))
                    bad = 1
            litems, vitems = dict(trophy_items("legacy-GM", pattern, folder)), dict(trophy_items("vanilla-5.x", pattern, folder))
            lt = {n: arm.split_tags(arm.blank_comments(e)) for _, e, n in
                  [(0, ltext[s:e], re.search(r'\bname\s*=\s*"([^"]+)"', h).group(1)) for s, e, h in arm.item_spans(arm.blank_comments(ltext))]}
            vt = {n: arm.split_tags(arm.blank_comments(e)) for _, e, n in
                  [(0, vtext[s:e], re.search(r'\bname\s*=\s*"([^"]+)"', h).group(1)) for s, e, h in arm.item_spans(arm.blank_comments(vtext))]}
            for name in litems:
                if name not in vitems:
                    count("items not in 5.x")
                    continue
                ft = arm.split_tags(arm.blank_comments(gm_i[name])) if name in gm_i else vt[name]
                if ("Quest" in ft) == ("Quest" in lt[name]):
                    count("trophy items: Quest tag as legacy's")
                elif feature not in PORTED:
                    count("%s not ported yet (Quest tag)" % feature)
                else:
                    print("DIFF %s: item %s: Quest %s (legacy: %s)" % (folder, name, "Quest" in ft, "Quest" in lt[name]))
                    bad = 1
                if litems[name] != vitems[name]:
                    print("DIFF %s: item %s: abilities %s (legacy %s)" % (folder, name, vitems[name], litems[name]))
                    bad = 1
        for k, v in sorted(counts.items()):
            print("%s: %d %s" % (folder, v, k))
    print("verify:", "differences found" if bad else "no difference")
    return bad


def main():
    ap = argparse.ArgumentParser()
    paths.add_worktree(ap)  # required: parallel areas each pass their own worktree
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--verify", action="store_true")
    a = ap.parse_args()
    if a.verify:
        sys.exit(verify(a.worktree))
    bad = 0
    outs = [(os.path.join(a.worktree, DLC, f, OUT), build(f)) for f in ["items", "items_plus"]]
    outs.append((os.path.join(a.worktree, TESTS), build_tests()))
    for path, text in outs:
        old = open(path, encoding="utf-8", newline="").read() if os.path.exists(path) else None
        if a.check:
            if old != text:
                print("out of date:", path)
                bad = 1
        elif old != text:
            with open(path, "w", encoding="utf-8", newline="") as f:
                f.write(text)
            print("wrote", path)
    sys.exit(bad)


if __name__ == "__main__":
    main()
