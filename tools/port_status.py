r"""Generate docs/5.x-file-status.md: how game version 5.x affects Ghost Mode's files.

Compares three trees:
    base  where legacy-GM and vanilla-5.x branch off master (legacy 1.32 vanilla files)
    mod   legacy-GM            legacy Ghost Mode v4.0 on top of the base
    new   vanilla-5.x          current 5.x vanilla files on top of the base

For every file Ghost Mode modifies it reports what 5.x did to the same file
(identical / encoding or whitespace only / changed / binary changed / deleted)
and whether `git merge -X ignore-all-space` of the mod onto 5.x merges it
cleanly or conflicts. It also lists vanilla files added and deleted in 5.x.

Usage:
    python tools/port_status.py [--mod REF] [--new REF] [--out docs/5.x-file-status.md]
"""
import argparse
import codecs
import collections
import os
import re
import subprocess

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PREFIX = "modGhostMode/"
TEXT_EXTS = (".ws", ".xml", ".csv")
LICENSE_HEADER = re.compile(r"\A(\s*/\*\*.*?\n)+", re.S)

# Order used for sections and summary rows.
STATUSES = ["deleted in 5.x", "changed", "whitespace/header only", "encoding/EOL only", "identical", "binary changed"]


def git(*args):
    return subprocess.check_output(["git", "-C", REPO, *args])


def tree(rev):
    files = {}
    for line in git("ls-tree", "-r", "-z", rev).split(b"\0"):
        if line:
            meta, path = line.split(b"\t", 1)
            files[path.decode()] = meta.split()[2].decode()
    return files


def decode(blob):
    if blob.startswith(codecs.BOM_UTF16_LE):
        blob = blob.decode("utf-16").encode()
    if blob.startswith(codecs.BOM_UTF8):
        blob = blob[len(codecs.BOM_UTF8):]
    return blob.decode("utf-8", "replace").replace("\r\n", "\n")


def classify(path, base, new):
    if path not in new:
        return "deleted in 5.x"
    if base[path] == new[path]:
        return "identical"
    if not path.endswith(TEXT_EXTS):
        return "binary changed"
    a, b = decode(git("cat-file", "blob", base[path])), decode(git("cat-file", "blob", new[path]))
    if a == b:
        return "encoding/EOL only"
    if path.endswith(".ws"):
        a, b = LICENSE_HEADER.sub("", a), LICENSE_HEADER.sub("", b)
    return "whitespace/header only" if a.split() == b.split() else "changed"


def merge_conflicts(mod, new):
    r = subprocess.run(["git", "-C", REPO, "merge-tree", "--write-tree", "--name-only",
                        "-X", "ignore-all-space", mod, new], capture_output=True, text=True)
    return set(re.findall(r"CONFLICT \([^)]*\): Merge conflict in (\S+)", r.stdout))


def short(path):
    return path[len(PREFIX):]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mod", default="legacy-GM", help="ref with the legacy Ghost Mode files")
    ap.add_argument("--new", default="vanilla-5.x", help="ref with the new vanilla files")
    ap.add_argument("--out", default=os.path.join(REPO, "docs", "5.x-file-status.md"))
    args = ap.parse_args()

    base_rev = git("merge-base", args.mod, args.new).decode().strip()
    new_title = git("log", "-1", "--format=%s", args.new).decode().strip()
    base, mod, new = tree(base_rev), tree(args.mod), tree(args.new)
    conflicts = merge_conflicts(args.mod, args.new)

    modified = sorted(p for p in mod if p.startswith(PREFIX) and p in base and base[p] != mod[p])
    added_by_mod = sorted(p for p in mod if p.startswith(PREFIX) and p not in base)
    rows = [(p, classify(p, base, new), p in conflicts) for p in modified]

    vanilla_common = sorted(p for p in set(base) & set(new) if p.startswith(PREFIX))
    vanilla_summary = collections.Counter((os.path.splitext(p)[1], classify(p, base, new)) for p in vanilla_common)
    vanilla_added = sorted(p for p in new if p.startswith(PREFIX) and p not in base)
    vanilla_deleted = sorted(p for p in base if p.startswith(PREFIX) and p not in new)

    out = []
    w = out.append
    w("# Ghost Mode files vs game version 5.x\n")
    w("Generated by `python tools/port_status.py`; do not edit by hand. "
      f"Compares the legacy vanilla files on `master`, `{args.mod}` (legacy Ghost Mode) and `{args.new}` ({new_title}).\n")
    w("Status is what 5.x did to the vanilla file, ignoring encoding and line endings:\n")
    w("- **changed**: real content changes; the Ghost Mode edits must be reviewed against them.")
    w("- **whitespace/header only**: only indentation, blank lines, BOM or the script license header differ.")
    w("- **binary changed**: binary resource (w2ent, ...) differs; all 5.x CR2W files use a newer format version.")
    w("- **merge**: result of `git merge-tree -X ignore-all-space <mod> vanilla-5.x`. "
      "`clean` means git can carry the Ghost Mode edits over automatically (still worth reviewing when 5.x also changed the file).\n")

    w("## Summary: files Ghost Mode modifies\n")
    w("| Type | 5.x status | Merge | Files |")
    w("|---|---|---|---|")
    summary = collections.Counter((os.path.splitext(p)[1], s, "conflict" if c else "clean") for p, s, c in rows)
    for (ext, status, merge), n in sorted(summary.items(), key=lambda kv: (kv[0][0], STATUSES.index(kv[0][1]), kv[0][2])):
        w(f"| `{ext}` | {status} | {merge} | {n} |")
    w(f"\nGhost Mode also adds {len(added_by_mod)} new files; "
      f"{sum(p in new for p in added_by_mod)} of those paths now exist in 5.x.\n")

    def section(title, items, note=""):
        w(f"## {title} ({len(items)})\n")
        if note:
            w(note + "\n")
        if not items:
            w("None.\n")
            return
        w("<details><summary>File list</summary>\n")
        for p in items:
            w(f"- `{short(p)}`")
        w("\n</details>\n")

    text_rows = [r for r in rows if r[0].endswith(TEXT_EXTS)]
    section("Text files that conflict", [p for p, s, c in text_rows if c],
            "Both Ghost Mode and 5.x changed overlapping lines. Port these by hand.")
    section("Text files 5.x changed that merge cleanly", [p for p, s, c in text_rows if not c and s == "changed"],
            "Git merges them, but 5.x changed the same file, so check the result still makes sense.")
    section("Text files 5.x only reformatted", [p for p, s, c in text_rows if s in ("whitespace/header only", "encoding/EOL only", "identical")],
            "Ghost Mode edits carry over mechanically (take 5.x's encoding and formatting).")
    section("Text files deleted in 5.x", [p for p, s, c in text_rows if s == "deleted in 5.x"])
    binary_rows = [p for p, s, c in rows if not p.endswith(TEXT_EXTS)]
    section("Binary files", binary_rows,
            "Ghost Mode ships edited copies of these legacy-format resources. They cannot be merged; "
            "the edits have to be reapplied to the 5.x files with a tool that can edit them (e.g. REDkit).")
    section("Files Ghost Mode adds", added_by_mod)

    w("## Vanilla changes from legacy to 5.x (whole baseline)\n")
    w("| Type | 5.x status | Files |")
    w("|---|---|---|")
    for (ext, status), n in sorted(vanilla_summary.items(), key=lambda kv: (kv[0][0], STATUSES.index(kv[0][1]))):
        w(f"| `{ext}` | {status} | {n} |")
    w("")
    section("Vanilla files added in 5.x", vanilla_added)
    section("Vanilla files deleted in 5.x", vanilla_deleted)

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
