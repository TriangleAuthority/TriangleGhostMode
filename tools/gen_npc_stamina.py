"""Generate Ghost Mode's NPC stamina overrides (STAM-08) from legacy's ability XML.

For every <ability> in the listed files whose stamina nodes legacy Ghost Mode changed
(vanilla-1.32 vs legacy-GM), write a DLC entry with on_conflict="extend" holding
the stamina nodes (tags containing "stamina") legacy changed, with legacy's values; nodes of
other tags keep 5.x's values. Nodes legacy removed are written with min/max 0 (ability values
add up, so 0 is neutral), unless 5.x no longer has them either. Only
stamina nodes are taken; the abilities' other Ghost Mode changes belong to other features.

Checks against vanilla-5.x and reports abilities 5.x no longer has, and conflicts: tags both
5.x and legacy changed from 1.32 (legacy's value is written; review them).

    python tools/gen_npc_stamina.py --worktree DIR [--check]

Writes modGhostMode/files/dlc/dlcghostmode/data/gameplay/abilities/gm_npc_stamina.xml in the
port's worktree (--worktree, required); --check prints the report and fails if the file is out of date. Then run
tools/gen_ngplus.py for the New Game+ copy.
"""
import argparse, os, re, subprocess, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = [
    "modGhostMode/files/gameplay/abilities/monster_base_abl.xml",
    "modGhostMode/files/gameplay/abilities/monster_base_abl_new.xml",
    "modGhostMode/files/gameplay/abilities/opp_base_abl.xml",
    "modGhostMode/files/gameplay/abilities/common_abilities.xml",
    "modGhostMode/files/dlc/ep1/data/gameplay/abilities/monster_base_abl.xml",
    "modGhostMode/files/dlc/ep1/data/gameplay/abilities/opp_base_abl.xml",
    "modGhostMode/files/dlc/bob/data/gameplay/abilities/monster_bob_base_abl.xml",
]
OUT = "modGhostMode/files/dlc/dlcghostmode/data/gameplay/abilities/gm_npc_stamina.xml"
ABILITY = re.compile(r'<ability\s+name="([^"]+)"[^>]*>(.*?)</ability>', re.S)
# Abilities another feature gives whole in its own DLC file (an expansion's ability loses its
# attributes and tags with extend): left out here.
OWNED = {"Mutation4BloodDebuff": "MUT-08, gm_mutations.xml"}
# AI's abilities given whole by gen_ai.py, with legacy's stamina values in them (ai.md's PA2).
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_ai import owned as _ai_owned  # noqa: E402
OWNED.update({n: "AI, " + f for n, f in _ai_owned().items()})
# DIFF's abilities given whole by gen_diff.py (diff.md's PD2): difficulty_CommonHardcore, legacy's entry,
# has no stamina regen node (STAM-08's "Stamina regen for AI no longer boosted for DM").
from gen_diff import owned as _diff_owned  # noqa: E402
import paths  # noqa: E402  (tools/: the shared --worktree argument)
OWNED.update({n: "DIFF, " + f for n, f in _diff_owned().items()})
NODE = re.compile(r'<([A-Za-z_][\w]*)\b([^>]*?)/>')


def show(rev, path):
    r = subprocess.run(["git", "show", f"{rev}:{path}"], cwd=REPO, capture_output=True)
    if r.returncode:
        return None
    return r.stdout.decode("utf-8-sig", errors="replace")


def stamina_nodes(body):
    """[(tag, attrs)] of the stamina nodes, in order; comments stripped."""
    body = re.sub(r"<!--.*?-->", "", body, flags=re.S)
    return [(m.group(1), " ".join(m.group(2).split())) for m in NODE.finditer(body) if "stamina" in m.group(1).lower()]


def abilities(text):
    return {m.group(1): stamina_nodes(m.group(2)) for m in ABILITY.finditer(text or "")}


def neutral(attrs):
    attrs = re.sub(r'min="[^"]*"', 'min="0"', attrs)
    return re.sub(r'max="[^"]*"', 'max="0"', attrs)


def per_tag(nodes):
    out = {}
    for tag, attrs in nodes:
        out.setdefault(tag, []).append(attrs)
    return out


def changes(old, new, v5):
    """The tags legacy changed: legacy's nodes for each (removed ones neutralised), in order.
    A tag legacy removed that 5.x no longer has is skipped. Returns (nodes, conflicts)."""
    o, n, f = per_tag(old), per_tag(new), per_tag(v5)
    out, conflicts = [], []
    for tag in dict.fromkeys([t for t, _ in old] + [t for t, _ in new]):
        if o.get(tag, []) == n.get(tag, []):
            continue
        if not n.get(tag) and not f.get(tag):
            continue
        if f.get(tag, []) != o.get(tag, []):
            conflicts.append(tag)
        a, b = n.get(tag, []), o.get(tag, [])
        for i in range(max(len(a), len(b))):
            out.append((tag, a[i] if i < len(a) else neutral(b[i]), i >= len(a)))
    return out, conflicts


def main():
    ap = argparse.ArgumentParser()
    paths.add_worktree(ap)  # required: parallel areas each pass their own worktree
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             "<!-- Ghost Mode: NPC stamina values (STAM-08), generated by tools/gen_npc_stamina.py from legacy",
             "     Ghost Mode's ability XML. Only stamina nodes; nodes legacy removed are 0. Do not edit by hand. -->",
             "<redxml>", "  <definitions>", "    <abilities>"]
    total = removed = 0
    for path in FILES:
        old, new, v5 = abilities(show("vanilla-1.32", path)), abilities(show("legacy-GM", path)), abilities(show("vanilla-5.x", path))
        changed = [a for a in new if new[a] != old.get(a, [])]
        if not changed:
            continue
        lines.append(f"      <!-- {path.split('files/', 1)[1]} -->")
        for a in changed:
            if a not in old:
                print(f"skip (added by legacy, not in 1.32): {a}")
                continue
            if a not in v5:
                print(f"skip (not in 5.x): {a}")
                continue
            if a in OWNED:
                print(f"skip (given whole by {OWNED[a]}): {a}")
                continue
            nodes, conflicts = changes(old[a], new[a], v5[a])
            if not nodes:
                continue
            for tag in conflicts:
                print(f"conflict: {a}.{tag}: 1.32 {per_tag(old[a]).get(tag)} | 5.x {per_tag(v5[a]).get(tag)} | legacy {per_tag(new[a]).get(tag)} (legacy written)")
            lines.append(f'      <ability name="{a}" on_conflict="extend">')
            for tag, attrs, gone in nodes:
                lines.append(f"        <{tag} {attrs} />" + ("  <!-- removed by legacy -->" if gone else ""))
                removed += gone
            lines.append("      </ability>")
            total += 1
    lines += ["    </abilities>", "  </definitions>", "</redxml>", ""]
    print(f"{total} abilities, {removed} removed nodes neutralised")
    if args.check:  # out of date: fail (gen_all.py --check relies on it)
        dst = os.path.join(args.worktree, OUT)
        if not os.path.exists(dst) or open(dst, encoding="utf-8-sig").read() != "\n".join(lines):
            sys.exit(f"out of date: {OUT}: run python tools/gen_npc_stamina.py")
    if not args.check:
        dst = os.path.join(args.worktree, OUT)
        with open(dst, "w", encoding="utf-8-sig", newline="\r\n") as f:
            f.write("\n".join(lines))
        print("wrote", dst)


if __name__ == "__main__":
    main()
