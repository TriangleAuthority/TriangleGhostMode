"""Generate the test dummy's step abilities (gm_test_dummy.xml in Ghost Mode's DLC) and the script
lookup of their names (tests/gmTestDummySteps.ws).

The in-game test dummy (modGhostMode/scripts/local/gm/tests/gmTestDummy.ws) sets an NPC's
armor, resistances, health, attack power and difficulty multiplier to exact values by adding
"step" abilities in counts: one ability per stat, sign and scale (e.g. GMTD_armor_p1 adds +1
armor, GMTD_fire_resistance_perc_n0.01 adds -1% fire resistance). Only the test scripts add
them, so no real enemy is affected. See docs/development.md#testing-in-game.

Usage:
    python tools/gen_test_dummy.py [--worktree ../TGM-5x-GM]
"""
import argparse
from pathlib import Path

DEST = "modGhostMode/files/dlc/dlcghostmode/data/gameplay/abilities/gm_test_dummy.xml"
DEST_WS = "modGhostMode/scripts/local/gm/tests/gmTestDummySteps.ws"

POINT_TYPES = ["physical", "poison", "fire", "frost", "shock", "force", "slashing",
               "piercing", "bludgeoning", "rending", "elemental"]
PERC_TYPES = POINT_TYPES + ["bleeding", "will", "burning"]
DOT_PERC = ["burning_DoT_damage_resistance_perc", "poison_DoT_damage_resistance_perc",
            "bleeding_DoT_damage_resistance_perc"]

BIG = [1000, 100, 10, 1, 0.1, 0.01]          # armor, resistance points, health
SMALL = [1, 0.1, 0.01, 0.001, 0.0001]        # resistance %, attack power, multipliers

# (stat, XML type, scales); the order matches GMTestDummyStats() in the script.
STATS = ([("armor", "add", BIG)]
         + [(t + "_resistance", "add", BIG) for t in POINT_TYPES]
         + [(t + "_resistance_perc", "add", SMALL) for t in PERC_TYPES]
         + [(n, "add", SMALL) for n in DOT_PERC]
         + [("vitality", "add", BIG), ("essence", "add", BIG),
            ("attack_power", "mult", SMALL), ("damage_final_multiplier", "add", SMALL),
            ("critical_hit_damage_reduction", "mult", SMALL)]
         # The point names of bleeding, will and burning resistance, which only Ghost Mode's EFX-08
         # makes the game read (after the others, so the earlier stats keep their order).
         + [(t + "_resistance", "add", BIG) for t in ["bleeding", "will", "burning"]])

# Other test-only abilities (name, attribute, XML type, value), not stats the dummy sets: XP-05's check that no
# script reads an NPC's experience attribute (tests/gmTestsXp.ws) adds +1000 experience and nothing else.
EXTRA = [("GMTD_experience_p1000", "experience", "add", 1000)]


def tag(x):
    return ("%g" % x)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--worktree", default="../TGM-5x-GM", help="the 5.x-GM worktree")
    args = ap.parse_args()
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             "<!-- Generated by tools/gen_test_dummy.py; do not edit by hand. Test-only step abilities for",
             "     the in-game test dummy (tests/gmTestDummy.ws): only test scripts add them. -->",
             "<redxml>", "  <definitions>", "    <abilities>"]
    count = 0
    for stat, typ, scales in STATS:
        for s in scales:
            for sign, val in (("p", s), ("n", -s)):
                lines.append('      <ability name="GMTD_%s_%s%s"><%s type="%s" always_random="false" min="%s" max="%s" /></ability>'
                             % (stat, sign, tag(s), stat, typ, tag(val), tag(val)))
                count += 1
    for n, attr, typ, val in EXTRA:
        lines.append('      <ability name="%s"><%s type="%s" always_random="false" min="%s" max="%s" /></ability>'
                     % (n, attr, typ, tag(val), tag(val)))
        count += 1
    lines += ["    </abilities>", "  </definitions>", "</redxml>", ""]
    out = Path(args.worktree) / DEST
    out.write_text("\n".join(lines), encoding="utf-8-sig")  # the game's XML carries a BOM
    print("wrote %s: %d abilities" % (out, count))
    ws = ["// Generated by tools/gen_test_dummy.py; do not edit by hand. The names of the test dummy's step",
          "// abilities (gm_test_dummy.xml) for one stat and sign, largest scale first, with their scales",
          "// (WitcherScript cannot build a name from a string).",
          "// One function per stat: a single large function exhausts the script compiler's memory.",
          "function GMTestDummySteps(stat : name, negative : bool, out names : array<name>, out scales : array<float>)",
          "{", "\tnames.Clear();", "\tscales.Clear();"]
    for i, (stat, typ, scales) in enumerate(STATS):
        ws.append("\tif(stat == '%s') { GMTestDummySteps%d(negative, names, scales); return; }" % (stat, i))
    ws += ["}", ""]
    for i, (stat, typ, scales) in enumerate(STATS):
        ws += ["function GMTestDummySteps%d(negative : bool, out names : array<name>, out scales : array<float>)" % i, "{"]
        for x in scales:
            ws.append("\tif(negative) names.PushBack('GMTD_%s_n%s'); else names.PushBack('GMTD_%s_p%s');"
                      % (stat, tag(x), stat, tag(x)))
            ws.append("\tscales.PushBack(%s);" % tag(x))
        ws += ["}", ""]
    out_ws = Path(args.worktree) / DEST_WS
    out_ws.write_text("\n".join(ws), encoding="utf-8")
    print("wrote %s" % out_ws)


if __name__ == "__main__":
    main()
